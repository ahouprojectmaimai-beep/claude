import { describe, expect, it } from "vitest";
import { parseCashCheckMessage } from "../src/matching/cashCheck";

const p = (t: string, on = "2026-10-02") => parseCashCheckMessage(t, on, 31);

describe("事務員の「現金チェックOK」メッセージ解析", () => {
  it.each([
    ["9/28〜9/30分 現金チェックOK", "2026-09-28", "2026-09-30"],
    ["9/28～9/30分　現金チェックOKです", "2026-09-28", "2026-09-30"],
    ["９/２８〜９/３０分 現金チェックＯＫ", "2026-09-28", "2026-09-30"],
    ["9月28日〜30日分 現金チェックOK", "2026-09-28", "2026-09-30"],
    ["28日〜30日分 現金チェックOK", "2026-09-28", "2026-09-30"],
    ["9/28-30 現金チェックOK", "2026-09-28", "2026-09-30"],
    ["9/30分 現金チェックOK", "2026-09-30", "2026-09-30"],
    ["9/28から9/30分 現金チェックOK", "2026-09-28", "2026-09-30"],
    ["9/29〜10/1分 現金チェックOK", "2026-09-29", "2026-10-01"],
  ])("%s", (t, from, to) => expect(p(t)).toEqual({ kind: "ok", from, to }));

  it("年またぎ（1月に受信した12月分）", () => {
    expect(p("12/29〜1/2分 現金チェックOK", "2027-01-05")).toEqual({ kind: "ok", from: "2026-12-29", to: "2027-01-02" });
  });
  it("関係ないメッセージは対象外", () => {
    expect(p("お疲れさまです！").kind).toBe("not_cash_check");
    expect(p("現金チェックお願いします").kind).toBe("not_cash_check");
  });
  it.each([
    "現金チェックOK",
    "9/1、9/3、9/5分 現金チェックOK",
    "9/30〜9/28分 現金チェックOK",
    "8/1〜9/30分 現金チェックOK",
    "9/28 9/30分 現金チェックOK",
  ])("解釈できない書き方は error（推測しない）: %s", (t) => expect(p(t).kind).toBe("error"));
});
